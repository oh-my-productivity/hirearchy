#!/bin/zsh
# P2 safety snapshot (P1's, with P2's products, protocol and sandbox root; read-only). Usage: safety-snapshot.sh <label>   -> prints to stdout
# Content per P1 protocol 7 (E3's snapshot + E4 additions), with P2's product shas (3d6b28aa, the arm-C worktree aac6af1b), P2's protocol path and the /tmp/hirearchy-p2/ listing. Never modifies anything it lists.
label="${1:-snapshot}"
REPO=/Volumes/workspace/hirearchy
PROTO=$REPO/studies/P2-retro-and-growth/evidence/protocol.md
REPO_C=/Volumes/workspace/hirearchy/.worktrees/p2-arm-c
echo "label: $label"
echo "date: $(date)"
echo "date_utc: $(date -u +%Y-%m-%dT%H:%M:%SZ)  epoch: $(date +%s)"
echo "kiro-cli: $(kiro-cli --version)"
echo "== md5 of files under ~/.kiro/settings (contents not printed)"
for f in ~/.kiro/settings/*(.N); do md5 "$f"; done
echo "== md5 ~/.kiro/skills/hirearchy/SKILL.md (global skill; read-only; absent while an arm-C stream has it aside, protocol 1)"
md5 ~/.kiro/skills/hirearchy/SKILL.md 2>&1
echo "== md5 ~/.kiro/memories/memories.db (a change is recorded, not attributed)"
md5 ~/.kiro/memories/memories.db
ls -la ~/.kiro/memories
echo "== ls -la ~/.kiro/agents"
ls -la ~/.kiro/agents
echo "== md5 ~/.kiro/agents/*"
for f in ~/.kiro/agents/*(.N); do md5 "$f"; done
echo "== hirearchy-* profiles in ~/.kiro/agents (pre-existing vs generated by P2: hirearchy-study-p2-*)"
ls -1 ~/.kiro/agents | grep '^hirearchy-' || echo "(none)"
echo "== ls ~/.kiro/skills"
ls ~/.kiro/skills
echo "== ls ~/.kiro/steering"
ls ~/.kiro/steering 2>&1
echo "== ls -la /Users/aminalizadeh/organization (read-only listing)"
ls -la /Users/aminalizadeh/organization
echo "== recursive file count and newest mtime of /Users/aminalizadeh/organization"
find /Users/aminalizadeh/organization -type f | wc -l
find /Users/aminalizadeh/organization -type f -exec stat -f '%m %N' {} + | sort -rn | head -1
echo "== tree digest of /Users/aminalizadeh/organization (md5 over sorted 'mtime size path' lines; stat only)"
find /Users/aminalizadeh/organization -type f -exec stat -f '%m %z %N' {} + | sort -k3 | md5
echo "== git status --porcelain (repo)"
git -C $REPO status --porcelain
echo "== git HEAD"
git -C $REPO rev-parse HEAD
echo "== git diff --stat 3d6b28aa HEAD -- src skills pyproject.toml uv.lock (arm R); arm C HEAD and status"
git -C $REPO diff --stat 3d6b28aa HEAD -- src skills pyproject.toml uv.lock; git -C $REPO_C rev-parse HEAD; git -C $REPO_C status --porcelain
echo "== md5 protocol.md"
md5 $PROTO
echo "== other orgs"
ls -d /Volumes/workspace/orgs
ls -la /Volumes/workspace/orgs
echo "== /tmp/hirearchy-p2/* (the study sandbox root; names only)"
g0dirs=(/tmp/hirearchy-p2/*(N))
if (( ${#g0dirs} )); then print -rl -- ${g0dirs:t}; else echo "(none)"; fi
