"""Class-interface check: every class with behaviour defined in ``src/orgmcp`` must subclass a ``typing.Protocol``.

Principle (refactor-principles.md, "D"): ``class FsMessageStore(MessageStore): ...``. Today almost no class does, so the
classes that do not are listed in ``interface_allowlist.txt`` (one ``module.Qualname`` per line). Each refactor step
removes entries; the end state is an EMPTY list.

* ``test_no_new_class_without_an_interface`` (active): fails only for a class that is NOT on the allow-list.
* ``test_every_class_has_an_interface`` (report): xfails while the allow-list is not empty, and passes (as a hard
  assertion) once it is empty. ``pytest -rx tests/golden/test_class_interfaces.py`` shows the count; set
  ``ORGMCP_INTERFACE_REPORT=1`` (with ``-s``) to print every offender and every stale allow-list entry.
* Stale entries (on the list but gone, exempt or compliant now) are reported, not failed; prune them with
  ``ORGMCP_INTERFACE_ALLOWLIST=rewrite uv run pytest tests/golden/test_class_interfaces.py`` (rewrites the list from
  the current offenders: a diff that ADDS a line is a review failure; the list may only shrink).

Exempt (data or framework, not behaviour):

* a Protocol itself (it IS the interface);
* exceptions (``BaseException`` subclasses);
* framework subclasses: any base from ``textual`` (widgets, screens, the App);
* pure data: a dataclass / ``NamedTuple`` / ``Enum`` / ``TypedDict`` whose own namespace has no behaviour: only fields,
  dunder methods (``__post_init__`` ...) and properties. A data class with a plain method, a classmethod or a
  staticmethod (``Message.load``, ``Message.render`` ...) has behaviour and is checked like any other class.

Limits: only classes reachable as module attributes (and their nested classes) are seen; a class defined inside a
function is not. Modules named ``tests`` / ``*.tests.*`` (colocated tests) and ``__main__`` are skipped.
"""

from __future__ import annotations

import dataclasses
import enum
import functools
import importlib
import inspect
import os
import pkgutil
import typing
from pathlib import Path

import pytest

import orgmcp

ALLOWLIST = Path(__file__).with_name("interface_allowlist.txt")
FRAMEWORK_ROOTS = ("textual",)
GENERATED = {"_make", "_replace", "_asdict", "_fields", "_field_defaults", "_source"}  # namedtuple/Enum internals
REPORT = os.environ.get("ORGMCP_INTERFACE_REPORT", "").strip() not in ("", "0")
REWRITE = os.environ.get("ORGMCP_INTERFACE_ALLOWLIST", "") == "rewrite"


# --------------------------------------------------------------------------------------------------- the walk


def source_modules() -> list[str]:
    names = []
    for info in pkgutil.walk_packages(orgmcp.__path__, "orgmcp."):
        parts = info.name.split(".")
        if "tests" in parts or parts[-1] == "__main__":
            continue
        names.append(info.name)
    return sorted(names)


def classes_of(module) -> list[type]:
    """Classes defined in ``module`` (not imported into it), nested ones included."""
    found: dict[str, type] = {}

    def visit(cls: type) -> None:
        if cls.__module__ != module.__name__ or found.get(f"{cls.__module__}.{cls.__qualname__}") is cls:
            return
        found[f"{cls.__module__}.{cls.__qualname__}"] = cls
        for value in vars(cls).values():
            if inspect.isclass(value):
                visit(value)

    for value in vars(module).values():
        if inspect.isclass(value):
            visit(value)
    return list(found.values())


def is_protocol_class(cls: type) -> bool:
    return bool(getattr(cls, "_is_protocol", False))


def subclasses_a_protocol(cls: type) -> bool:
    return any(base is not cls and is_protocol_class(base) and base not in (typing.Protocol, typing.Generic) and
               base.__module__ != "typing" for base in cls.__mro__)


def behaviour_of(cls: type) -> list[str]:
    """Own methods that are behaviour: not dunder, not generated by namedtuple/Enum, not a (cached) property."""
    data_like = issubclass(cls, (tuple, enum.Enum)) and not dataclasses.is_dataclass(cls)
    out = []
    for name, value in vars(cls).items():
        if (name.startswith("__") and name.endswith("__")) or (data_like and (name in GENERATED or name.startswith("_"))):
            continue
        if isinstance(value, (property, functools.cached_property)):
            continue
        if isinstance(value, (staticmethod, classmethod)) or inspect.isfunction(value):
            out.append(name)
    return out


def is_pure_data(cls: type) -> bool:
    kinds = dataclasses.is_dataclass(cls) or issubclass(cls, enum.Enum) or (issubclass(cls, tuple) and hasattr(cls, "_fields")) \
        or typing.is_typeddict(cls)
    return bool(kinds) and not behaviour_of(cls)


def exemption(cls: type) -> str | None:
    if is_protocol_class(cls):
        return "protocol"
    if issubclass(cls, BaseException):
        return "exception"
    if any(base.__module__.split(".")[0] in FRAMEWORK_ROOTS for base in cls.__mro__[1:]):
        return "framework"
    if is_pure_data(cls):
        return "data"
    return None


def survey() -> tuple[dict[str, str], dict[str, int]]:
    """({offender: why} for classes with behaviour and no Protocol base, {exemption: count} + 'compliant')."""
    offenders: dict[str, str] = {}
    counts = {"protocol": 0, "exception": 0, "framework": 0, "data": 0, "compliant": 0}
    for name in source_modules():
        module = importlib.import_module(name)
        for cls in classes_of(module):
            why = exemption(cls)
            if why:
                counts[why] += 1
            elif subclasses_a_protocol(cls):
                counts["compliant"] += 1
            else:
                offenders[f"{cls.__module__}.{cls.__qualname__}"] = "no Protocol base"
    return offenders, counts


def allowed() -> set[str]:
    if not ALLOWLIST.is_file():
        return set()
    lines = (line.split("#", 1)[0].strip() for line in ALLOWLIST.read_text(encoding="utf-8").splitlines())
    return {line for line in lines if line}


def write_allowlist(offenders: set[str]) -> None:
    head = (
        "# Classes with behaviour that do not yet subclass a typing.Protocol (see test_class_interfaces.py).\n"
        "# One module.Qualname per line. Refactor steps REMOVE entries; the end state is an empty list.\n"
    )
    ALLOWLIST.write_text(head + "".join(f"{name}\n" for name in sorted(offenders)), encoding="utf-8")


# ----------------------------------------------------------------------------------------------------- tests


@pytest.fixture(scope="module")
def surveyed():
    offenders, counts = survey()
    if REWRITE:
        write_allowlist(set(offenders))
    return offenders, counts


def test_no_new_class_without_an_interface(surveyed):
    offenders, counts = surveyed
    listed = allowed()
    new = sorted(set(offenders) - listed)
    stale = sorted(listed - set(offenders))
    if REPORT:
        print(f"\n{len(offenders)} class(es) without a Protocol base ({len(listed)} allow-listed); exempt/compliant: {counts}")
        print("\n".join(f"  no interface: {n}" for n in sorted(offenders)))
        print("\n".join(f"  stale allow-list entry (remove it): {n}" for n in stale))
    assert not new, (
        "these classes have behaviour but subclass no typing.Protocol (add the interface, or exempt them only if they are "
        "data/exceptions/framework classes; do NOT add them to interface_allowlist.txt):\n  " + "\n  ".join(new)
    )


def test_stale_allowlist_entries_are_listed_for_pruning(surveyed):
    """Not a failure (the list may only shrink, and a rename shows up above first); a warning with the names to remove."""
    offenders, _ = surveyed
    stale = sorted(allowed() - set(offenders))
    if stale:
        import warnings

        warnings.warn(f"interface_allowlist.txt has {len(stale)} stale entr(ies) to remove: {', '.join(stale)}", stacklevel=1)


def test_every_class_has_an_interface(surveyed):
    """The end-state assertion. Reported as xfail until the allow-list is empty, then a hard check."""
    offenders, counts = surveyed
    if offenders:
        pytest.xfail(f"{len(offenders)} class(es) with behaviour still lack a Protocol base "
                     f"(allow-list: {len(allowed())}; exempt/compliant: {counts}); ORGMCP_INTERFACE_REPORT=1 lists them")
    assert not allowed(), "all classes have interfaces: empty interface_allowlist.txt"


def test_the_exemption_rules_on_examples():
    """The classifier itself, on small classes (so a change of the rules is a visible change)."""

    class Port(typing.Protocol):
        def run(self) -> None: ...

    class Impl(Port):
        def run(self) -> None:
            return None

    @dataclasses.dataclass
    class Plain:
        x: int = 0

        def __post_init__(self) -> None: ...

        @property
        def double(self) -> int:
            return self.x * 2

    @dataclasses.dataclass
    class Smart:
        x: int = 0

        def compute(self) -> int:
            return self.x

    class Named(typing.NamedTuple):
        a: int

    class Color(enum.Enum):
        RED = 1

    class Boom(ValueError): ...

    class Service:
        def run(self) -> None: ...

    assert [exemption(c) for c in (Port, Impl, Plain, Smart, Named, Color, Boom, Service)] == [
        "protocol", None, "data", None, "data", "data", "exception", None]
    assert subclasses_a_protocol(Impl) and not subclasses_a_protocol(Service) and not subclasses_a_protocol(Port)
